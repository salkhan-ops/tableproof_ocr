"""Financial-statement-style tables (synthetic, Auditra Phase A set): gates that must hold.

Fixtures: data/financial_statements/*.pdf with *.gt.json (cell text as rendered), generated by
scripts/create_financial_statement_fixtures.py. Whole pages are reconstructed, as a caller that
has no table detector would do.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

from tableproof.models import ReconstructionOptions, WordBox
from tableproof.pdf_extractor import extract_words
from tableproof.table_reconstructor import reconstruct_table_grid

DATA = Path(__file__).resolve().parents[1] / "data" / "financial_statements"
CASES = [
    (gt, page)
    for gt in sorted(DATA.glob("*.gt.json"))
    for page in range(1, len(json.loads(gt.read_text())["pages"]) + 1)
]


def _grid(gt_path: Path, page: int):
    pdf = gt_path.with_name(gt_path.name.replace(".gt.json", ".pdf"))
    words = extract_words(pdf, page).words
    return reconstruct_table_grid(
        [WordBox(i, w.text, w.bbox) for i, w in enumerate(words)],
        options=ReconstructionOptions(profile="financial_statement"),
    )


@pytest.mark.parametrize(("gt_path", "page"), CASES, ids=lambda v: getattr(v, "stem", str(v)))
def test_no_word_is_hidden_and_labels_survive(gt_path: Path, page: int) -> None:
    grid = _grid(gt_path, page)
    nwl = grid.metrics["continuation_resolution"]["no_word_loss"]
    assert nwl["hidden_by_spans_word_indices"] == []
    assert nwl["passed"]
    tokens = {t for row in grid.matrix() for cell in row for t in (cell or "").split()}
    rows = json.loads(gt_path.read_text())["pages"][page - 1]
    for row in rows:
        for word in row[0].split():
            # Financial-statement profile: every label word is in an output cell.
            assert word in tokens, f"label word {word!r} is missing from the output"


@pytest.mark.parametrize(("gt_path", "page"), CASES, ids=lambda v: getattr(v, "stem", str(v)))
def test_amount_digits_are_verbatim(gt_path: Path, page: int) -> None:
    grid = _grid(gt_path, page)
    cells = {(cell or "").strip() for row in grid.matrix() for cell in row}
    tokens = {t for c in cells for t in c.split()}
    rows = json.loads(gt_path.read_text())["pages"][page - 1]
    for row in rows:
        for value in row[1:]:
            if re.fullmatch(r"\(?\d[\d,]*(\.\d+)?\)?", value or ""):
                assert value in cells or value in tokens, f"amount {value!r} altered or lost"
